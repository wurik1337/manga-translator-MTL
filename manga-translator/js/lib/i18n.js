/** Предпочтение пользователя: 'browser' (по умолчанию) или код языка. */
export function resolveUiLang(pref, browserLang) {
  if (pref && pref !== 'browser' && STRINGS[pref]) return pref;
  const bl = String(browserLang || 'en').toLowerCase();
  if (STRINGS[bl]) return bl;
  const base = bl.split('-')[0];
  return STRINGS[base] ? base : 'en';
}

/** Язык браузера: API расширения, иначе navigator.language. */
export function detectBrowserLang(nav) {
  try {
    if (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage) return chrome.i18n.getUILanguage();
  } catch (e) { /* вне расширения */ }
  return nav?.language || 'en';
}

/** Функция перевода с фолбэком на английский и подстановкой {переменных}. */
export function makeT(lang) {
  const d = STRINGS[lang] || STRINGS.en;
  return (key, vars) => {
    let s = d[key] ?? STRINGS.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

/** Применить словарь к DOM: data-i18n (текст), data-i18n-html (HTML),
 *  data-i18n-ph (placeholder), data-i18n-title (title). */
export function applyI18n(root, t) {
  for (const el of root.querySelectorAll('[data-i18n]')) {
    if (el.dataset.i18nSkip === '1') continue; // временные подписи (кнопки-подтверждения)
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
}
